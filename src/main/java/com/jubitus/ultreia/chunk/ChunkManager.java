package com.jubitus.ultreia.chunk;

import com.jubitus.ultreia.geom.Pos2D;
import com.google.common.collect.ImmutableSetMultimap;
import com.jubitus.ultreia.Ultreia;
import com.jubitus.ultreia.config.UltreiaConfig;
import it.unimi.dsi.fastutil.longs.LongOpenHashSet;
import net.minecraft.entity.player.EntityPlayer;
import net.minecraft.server.management.PlayerChunkMapEntry;
import net.minecraft.util.math.ChunkPos;
import net.minecraft.util.math.MathHelper;
import net.minecraft.world.WorldServer;
import net.minecraft.world.chunk.Chunk;
import net.minecraft.world.gen.ChunkProviderServer;
import net.minecraft.world.storage.ThreadedFileIOBase;
import net.minecraftforge.common.ForgeChunkManager;

public final class ChunkManager {

    // Only chunks WE force-loaded. Chunks already loaded by Millénaire or Minecraft are never
    // tracked here — they are not our responsibility to unload.
    private final LongOpenHashSet ours = new LongOpenHashSet();
    private final int edgeCap;
    // Forge caps the chunks per ticket (forgeChunkLoading.cfg): more tickets are requested as they fill.
    private final java.util.List<ForgeChunkManager.Ticket> tickets = new java.util.ArrayList<>();

    // Chunk loads since the last takePerfSummary() (logPerformance only): read from disk vs newly generated.
    private int perfDiskLoads, perfGenerated;
    private long perfDiskNs, perfGenNs, perfWorstGenNs;

    public ChunkManager(int edgeCap) {
        this.edgeCap = Math.max(0, edgeCap);
    }

    public boolean ensureLoaded(WorldServer world, int x, int z) {
        int cx = x >> 4;
        int cz = z >> 4;
        long k = Pos2D.xzKey(cx, cz);
        ChunkProviderServer cps = (ChunkProviderServer) world.getChunkProvider();

        // Already loaded by us or by someone else (Millénaire, players, etc.)
        if (ours.contains(k) || cps.getLoadedChunk(cx, cz) != null) {
            return true;
        }

        if (!UltreiaConfig.GENERAL.allowChunkLoading) return false;

        if (edgeCap > 0 && ours.size() >= edgeCap) {
            if (UltreiaConfig.DEBUG.logChunks) {
                Ultreia.LOGGER.warn("[Ultreia] Edge chunk cap ({}) reached, cannot load {},{}", edgeCap, cx, cz);
            }
            return false;
        }

        ForgeChunkManager.Ticket ticket = ticketWithRoom(world);
        if (ticket == null) return false;

        boolean perf = UltreiaConfig.DEBUG.logPerformance;
        boolean existed = perf && cps.isChunkGeneratedAt(cx, cz);
        long t0 = perf ? System.nanoTime() : 0L;
        try {
            ForgeChunkManager.forceChunk(ticket, new ChunkPos(cx, cz));
            cps.provideChunk(cx, cz);
        } catch (Throwable ignored) {}
        if (perf) recordLoad(existed, System.nanoTime() - t0);

        if (cps.getLoadedChunk(cx, cz) != null) {
            ours.add(k);
            return true;
        }
        return false;
    }

    /**
     * Called after each edge (success or failure).
     * Unforces our chunks and queues them for unload, then applies unload pressure to any
     * side-effect loads (chunk neighbors generated by MC, Millénaire ticks, etc.).
     * Actual chunk drop happens via the normal WorldServer.tick() → ChunkProviderServer.tick()
     * cycle — we never block the server thread waiting for I/O.
     */
    public void releaseEdge(WorldServer world) {
        if (world == null || ours.isEmpty()) return;

        ChunkProviderServer cps = (ChunkProviderServer) world.getChunkProvider();

        // Unforce all chunks we own so canDropChunk() can return true for them
        for (ForgeChunkManager.Ticket t : tickets) {
            for (ChunkPos pos : t.getChunkList()) {
                try { ForgeChunkManager.unforceChunk(t, pos); }
                catch (Throwable ignored) {}
            }
        }

        // Trigger async save for dirty chunks before queuing unloads
        try { cps.saveChunks(true); } catch (Throwable ignored) {}

        // Snapshot the forced-by-others map once to avoid redundant calls in the loop
        ImmutableSetMultimap<ChunkPos, ForgeChunkManager.Ticket> forced = snapshotForcedChunks(world);

        // Queue our chunks for unload
        int ownedQueued = 0;
        for (long k : ours) {
            int cx = Pos2D.xFromKey(k);
            int cz = Pos2D.zFromKey(k);
            Chunk ch = cps.getLoadedChunk(cx, cz);
            if (ch == null) continue;
            if (isWatchedByPlayers(world, cx, cz)) continue;
            if (isForcedByOthers(forced, new ChunkPos(cx, cz))) continue;
            try { cps.queueUnload(ch); ownedQueued++; }
            catch (Throwable ignored) {}
        }

        // Apply pressure to side-effect loads: queue any non-essential chunks for unload.
        // This catches chunks loaded by MC neighbor generation or Millénaire during our pathfinding.
        int sideEffectQueued = applyUnloadPressure(world, cps, forced);

        if (UltreiaConfig.DEBUG.logChunks) {
            Ultreia.LOGGER.debug(
                "[Ultreia] releaseEdge: owned={} queued={} sideEffect={} totalLoaded={}",
                ours.size(), ownedQueued, sideEffectQueued, cps.getLoadedChunkCount());
        }

        ours.clear();

        // Emergency drain: if loaded count is still far above the per-edge cap, help the queue.
        // Under normal operation the server's own cps.tick() drains the queue each game tick.
        int softLimit = Math.max(200, edgeCap > 0 ? edgeCap : UltreiaConfig.GENERAL.maxForcedChunksPerJob);
        if (cps.getLoadedChunkCount() > softLimit * 2) {
            for (int i = 0; i < 5; i++) {
                try { cps.tick(); } catch (Throwable ignored) { break; }
            }
            if (UltreiaConfig.DEBUG.logChunks) {
                Ultreia.LOGGER.debug("[Ultreia] Emergency drain pass, now {} chunks loaded", cps.getLoadedChunkCount());
            }
        }
    }

    /** Final cleanup when the generation job ends (normally or via crash). */
    public void close(WorldServer world) {
        if (world != null) {
            releaseEdge(world);
            // Wait for async I/O to flush all painted chunks to disk
            ChunkProviderServer cps = (ChunkProviderServer) world.getChunkProvider();
            try { cps.flushToDisk(); } catch (Throwable ignored) {}
            try { ThreadedFileIOBase.getThreadedIOInstance().waitForFinish(); } catch (Throwable ignored) {}
        }
        for (ForgeChunkManager.Ticket t : tickets) {
            try { ForgeChunkManager.releaseTicket(t); } catch (Throwable ignored) {}
        }
        tickets.clear();
        ours.clear();
    }

    private void recordLoad(boolean fromDisk, long ns) {
        if (fromDisk) {
            perfDiskLoads++;
            perfDiskNs += ns;
        } else {
            perfGenerated++;
            perfGenNs += ns;
            if (ns > perfWorstGenNs) perfWorstGenNs = ns;
        }
    }

    /** Chunk loads since the previous call, as one log fragment; resets the counters. */
    public String takePerfSummary() {
        String s = "chunks: " + perfDiskLoads + " from disk (" + perfDiskNs / 1_000_000L + " ms), "
                + perfGenerated + " generated (" + perfGenNs / 1_000_000L + " ms, worst "
                + perfWorstGenNs / 1_000_000L + " ms)";
        perfDiskLoads = perfGenerated = 0;
        perfDiskNs = perfGenNs = perfWorstGenNs = 0L;
        return s;
    }

    // Queues non-essential loaded chunks for unload — catches side-effect loads.
    private int applyUnloadPressure(WorldServer world, ChunkProviderServer cps,
                                    ImmutableSetMultimap<ChunkPos, ForgeChunkManager.Ticket> forced) {
        int queued = 0;
        try {
            for (Chunk c : cps.getLoadedChunks()) {
                if (ours.contains(Pos2D.xzKey(c.x, c.z))) continue; // still owned (shouldn't happen after unforce loop)
                if (isWatchedByPlayers(world, c.x, c.z)) continue;
                if (isForcedByOthers(forced, new ChunkPos(c.x, c.z))) continue;
                cps.queueUnload(c);
                queued++;
            }
        } catch (Throwable ignored) {}
        return queued;
    }

    private ImmutableSetMultimap<ChunkPos, ForgeChunkManager.Ticket> snapshotForcedChunks(WorldServer world) {
        try {
            return ForgeChunkManager.getPersistentChunksFor(world);
        } catch (Throwable ignored) {
            return null;
        }
    }

    private boolean isForcedByOthers(ImmutableSetMultimap<ChunkPos, ForgeChunkManager.Ticket> forced, ChunkPos pos) {
        if (forced == null || !forced.containsKey(pos)) return false;
        // Our own tickets don't count as "others"
        for (ForgeChunkManager.Ticket t : forced.get(pos)) {
            if (!tickets.contains(t)) return true;
        }
        return false;
    }

    private boolean isWatchedByPlayers(WorldServer world, int cx, int cz) {
        try {
            PlayerChunkMapEntry entry = world.getPlayerChunkMap().getEntry(cx, cz);
            if (entry != null) return true;
        } catch (Throwable ignored) {}
        try {
            int vd = world.getMinecraftServer().getPlayerList().getViewDistance() + 1;
            for (EntityPlayer p : world.playerEntities) {
                int pcx = MathHelper.floor(p.posX) >> 4;
                int pcz = MathHelper.floor(p.posZ) >> 4;
                if (Math.abs(pcx - cx) <= vd && Math.abs(pcz - cz) <= vd) return true;
            }
        } catch (Throwable ignored) {}
        return false;
    }

    @javax.annotation.Nullable
    private ForgeChunkManager.Ticket ticketWithRoom(WorldServer world) {
        if (!tickets.isEmpty()) {
            ForgeChunkManager.Ticket last = tickets.get(tickets.size() - 1);
            if (last.getChunkList().size() < last.getMaxChunkListDepth()) return last;
        }
        try {
            ForgeChunkManager.Ticket t = ForgeChunkManager.requestTicket(Ultreia.INSTANCE, world, ForgeChunkManager.Type.NORMAL);
            if (t != null) tickets.add(t);
            return t;
        } catch (Throwable t) {
            return null;
        }
    }

}
